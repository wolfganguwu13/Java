    private void BtnCalcActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnCalcActionPerformed
        int n = (Integer) Spn.getValue();
        
        int res = n % 2;
        LblRes.setText(Integer.toString(res));
        
        int cub = (n * n) * n;
        LblCub.setText(Integer.toString(cub));
        
        double quad = Math.sqrt(n);
        LblQuad.setText(String.format("%.2f", quad));
        
        double rcub = Math.cbrt(n);
        LblRcub.setText(String.format("%.2f", rcub));
        
        int vab = Math.abs(n);
        LblVab.setText(Integer.toString(vab));
        
    }//GEN-LAST:event_BtnCalcActionPerformed

